class Handler(BaseHTTPRequestHandler):
    def do_POST(self) -> None:  # noqa: N802
        length = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(length))
        user_text = next(
            (m["content"] for m in body.get("messages", []) if m["role"] == "user"), ""
        )
        content = None
        for marker, answer in RESPONSES:
            if marker in user_text:
                content = json.dumps(answer, ensure_ascii=False)
                break
        if content is None:
            self.send_response(400)
            self.end_headers()
            self.wfile.write("Заглушка не знает такой промпт".encode())
            return
        reply = {"choices": [{"message": {"role": "assistant", "content": content}}]}
        data = json.dumps(reply, ensure_ascii=False).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def log_message(self, fmt: str, *args) -> None:
        print(f"  запрос: {self.path}")


def main() -> None:
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8765
    server = HTTPServer(("127.0.0.1", port), Handler)
    print(f"Сервер-заглушка LLM: http://127.0.0.1:{port}/v1 (Ctrl+C — остановка)")
    server.serve_forever()


if __name__ == "__main__":
    main()
